"""The models.dev providers a customer may add a key for, each under its own name (OMN-26688).

The operator asked on 2026-11-26 for every API-key provider and chose one key per
provider. ``byok_catalog_providers.yaml`` beside this module is the shipped list:
one row per provider whose SDK package in models.dev is ``@ai-sdk/openai-compatible``
and whose base URL is a fixed ``https://`` URL. It is generated from a models.dev
copy by :func:`main` and committed, so the URL a customer's key is sent to is fixed
at release time and reviewed in the pull request, never read from a document fetched
at run time.

A provider is left out when:
  - models.dev gives it another SDK package (its own API shape) or no base URL;
  - its base URL is not ``https://``, names a template (an account id, a host), or is
    a server on the user's own machine;
  - its id is not a plain lower-case token (it becomes a secret reference);
  - a declared provider already serves its endpoint (z.ai is offered as ``glm``);
  - it is a coding, token, step or subscription plan, unless a row in
    ``byok_catalog_plan_rulings.yaml`` records the provider's own doc URL, the
    sentence that allows API-key use in other tools, and the date it was read. That
    file ships empty: each plan is ruled on one at a time with the operator's approval.

A provider the operator names that models.dev does not list is a row of
``byok_catalog_added_providers.yaml``, written by hand from the provider's own docs:
the same rules hold for it, and the row names the page it was read from and when.
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Iterable, Mapping
from functools import lru_cache
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import yaml
from pydantic import BaseModel, ConfigDict, Field

from omnimarket.handlers.routing.provider_feature_flags import provider_turned_off

CATALOG_PROVIDERS_PATH = Path(__file__).with_name("byok_catalog_providers.yaml")
PLAN_RULINGS_PATH = Path(__file__).with_name("byok_catalog_plan_rulings.yaml")
ADDED_PROVIDERS_PATH = Path(__file__).with_name("byok_catalog_added_providers.yaml")
ADDED_PROVIDERS_SCHEMA = "byok_catalog_added_providers.v1"
WITHHELD_PROVIDERS_PATH = Path(__file__).with_name(
    "byok_catalog_withheld_providers.yaml"
)
WITHHELD_PROVIDERS_SCHEMA = "byok_catalog_withheld_providers.v1"
CATALOG_PROVIDERS_SCHEMA = "byok_catalog_providers.v1"
PLAN_RULINGS_SCHEMA = "byok_catalog_plan_rulings.v1"
OPENAI_COMPATIBLE_PACKAGE = "@ai-sdk/openai-compatible"

_ID_PATTERN = r"^[a-z0-9][a-z0-9_-]*$"
_ID = re.compile(_ID_PATTERN)
#: A plan by id or name: "zai-coding-plan", "Kimi For Coding", "Alibaba Token Plan".
_PLAN = re.compile(r"\bplan\b|coding", re.IGNORECASE)
_LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "0.0.0.0", "::1"})

_HEADER = """\
# SPDX-FileCopyrightText: 2026 OmniNode.ai Inc.
# SPDX-License-Identifier: MIT
#
# GENERATED by `python -m omnimarket.handlers.routing.byok_catalog_providers
# <models.dev copy>` (OMN-26688). Do not edit by hand: change the rules in that
# module, regenerate, and review the diff. Each row is a provider a customer may
# add a key for under its own name; its key is sent only to `api`.
"""


class ModelByokCatalogProvider(BaseModel):
    """One provider from models.dev, offered under its own name and key."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str = Field(pattern=_ID_PATTERN)
    name: str = Field(min_length=1)
    #: The OpenAI-compatible base URL, without a trailing slash.
    api: str = Field(pattern=r"^https://[^\s${}\x00-\x1f\x7f]+[^/\s]$")
    #: The provider's own documentation page; onboarding guidance only.
    doc: str | None = Field(default=None, pattern=r"^https://[^\s\x00-\x1f\x7f]+$")

    @property
    def backend_id(self) -> str:
        return f"byok-{self.id}"

    @property
    def endpoint_url(self) -> str:
        return f"{self.api}/chat/completions"

    @property
    def models_url(self) -> str:
        return f"{self.api}/models"


class ModelByokCatalogPlanRuling(BaseModel):
    """The ruling that lets one coding or token plan be offered."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    provider: str = Field(pattern=_ID_PATTERN)
    #: The provider's own page the ruling rests on.
    doc_url: str = Field(pattern=r"^https://[^\s\x00-\x1f\x7f]+$")
    #: The sentence on that page that allows API-key use in other tools.
    quote: str = Field(min_length=1)
    read_on: str = Field(pattern=r"^\d{4}-\d{2}-\d{2}$")


class ModelByokCatalogAddedProvider(ModelByokCatalogProvider):
    """A provider the operator named, read from its own docs (not on models.dev)."""

    #: The provider's own page the base URL was read from.
    source: str = Field(pattern=r"^https://[^\s\x00-\x1f\x7f]+$")
    read_on: str = Field(pattern=r"^\d{4}-\d{2}-\d{2}$")

    def listed(self) -> ModelByokCatalogProvider:
        return ModelByokCatalogProvider(
            id=self.id, name=self.name, api=self.api, doc=self.doc
        )


class ModelByokCatalogWithheld(BaseModel):
    """A listed provider left out because its address was checked and does not
    work: offered, it would fail only after the user pasted a key."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    provider: str = Field(pattern=_ID_PATTERN)
    reason: str = Field(min_length=3)
    #: What the check saw, so the next reader can run it again.
    evidence: str = Field(min_length=3)
    checked_on: str = Field(pattern=r"^\d{4}-\d{2}-\d{2}$")


class ByokCatalogListError(ValueError):
    """The shipped provider list or the rulings file is missing or mis-shaped."""


def _is_plan(provider_id: str, name: str) -> bool:
    return bool(_PLAN.search(provider_id.replace("-", " ")) or _PLAN.search(name))


def _fixed_https_base(api: str) -> str | None:
    """The base URL without a trailing slash, or None when it must not be offered."""
    base = api.strip().rstrip("/")
    if not base.startswith("https://") or any(c in base for c in "${}"):
        return None
    host = urlsplit(base).hostname
    if not host or host in _LOCAL_HOSTS:
        return None
    return base


def _one_models_page(doc: str, models: object) -> bool:
    """A docs link to a page about one model (``.../models/<id>``), not the provider's."""
    segments = [s for s in urlsplit(doc).path.lower().split("/") if s]
    if "models" in segments[:-1]:
        return True
    if not segments or len(segments[-1]) <= 3 or not isinstance(models, Mapping):
        return False
    return any(segments[-1] in str(m).rsplit("/", 1)[-1].lower() for m in models)


def select_catalog_providers(
    document: Mapping[str, Any],
    *,
    declared_ids: frozenset[str],
    declared_hosts: frozenset[str],
    rulings: Iterable[ModelByokCatalogPlanRuling],
) -> tuple[ModelByokCatalogProvider, ...]:
    """The providers in a models.dev document that may be offered, sorted by id."""
    ruled = {ruling.provider for ruling in rulings}
    kept: list[ModelByokCatalogProvider] = []
    for provider_id, entry in document.items():
        if not isinstance(entry, Mapping):
            continue
        if entry.get("npm") != OPENAI_COMPATIBLE_PACKAGE:
            continue
        pid = str(provider_id)
        name = str(entry.get("name") or pid).strip()
        base = _fixed_https_base(str(entry.get("api") or ""))
        if base is None or not _ID.fullmatch(pid) or pid in declared_ids:
            continue
        if urlsplit(base).hostname in declared_hosts:
            continue
        if _is_plan(pid, name) and pid not in ruled:
            continue
        doc = str(entry.get("doc") or "").strip()
        if _one_models_page(doc, entry.get("models")):
            doc = ""
        kept.append(
            ModelByokCatalogProvider(
                id=pid,
                name=name,
                api=base,
                doc=doc if doc.startswith("https://") else None,
            )
        )
    return tuple(sorted(kept, key=lambda provider: provider.id))


def render_catalog_providers(providers: Iterable[ModelByokCatalogProvider]) -> str:
    """The shipped file's text for ``providers``: the one writer of that file."""
    rows = [
        provider.model_dump(exclude_none=True)
        for provider in sorted(providers, key=lambda provider: provider.id)
    ]
    body = yaml.safe_dump(
        {"schema_version": CATALOG_PROVIDERS_SCHEMA, "providers": rows},
        sort_keys=False,
        allow_unicode=True,
        width=4096,
    )
    return _HEADER + body


def _read_yaml(path: Path, schema: str) -> dict[str, Any]:
    if not path.is_file():
        raise ByokCatalogListError(f"{path.name} not found at {path}")
    raw: Any = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or raw.get("schema_version") != schema:
        raise ByokCatalogListError(f"{path} does not declare schema_version {schema!r}")
    return raw


@lru_cache(maxsize=1)
def load_byok_catalog_plan_rulings() -> tuple[ModelByokCatalogPlanRuling, ...]:
    """Every ruling that lets a coding or token plan be offered (empty in OMN-26688)."""
    rows = _read_yaml(PLAN_RULINGS_PATH, PLAN_RULINGS_SCHEMA).get("rulings")
    if not isinstance(rows, list):
        raise ByokCatalogListError(f"{PLAN_RULINGS_PATH} has no 'rulings' list")
    return tuple(ModelByokCatalogPlanRuling.model_validate(row) for row in rows)


@lru_cache(maxsize=1)
def load_byok_catalog_providers() -> dict[str, ModelByokCatalogProvider]:
    """Every provider offered from a list, by id: the generated models.dev list,
    then the operator's additions. Cached: both ship inside the wheel."""
    held = {w.provider for w in load_byok_catalog_withheld()}
    found = {
        pid: row
        for pid, row in load_generated_catalog_providers().items()
        if pid not in held
    }
    for added in load_byok_catalog_added_providers():
        if added.id in found:
            raise ByokCatalogListError(
                f"{added.id!r} is on the models.dev list now: remove its row from "
                f"{ADDED_PROVIDERS_PATH.name}"
            )
        found[added.id] = added.listed()
    return found


@lru_cache(maxsize=1)
def load_generated_catalog_providers() -> dict[str, ModelByokCatalogProvider]:
    """The generated models.dev list alone, by provider id."""
    rows = _read_yaml(CATALOG_PROVIDERS_PATH, CATALOG_PROVIDERS_SCHEMA).get("providers")
    if not isinstance(rows, list):
        raise ByokCatalogListError(f"{CATALOG_PROVIDERS_PATH} has no 'providers' list")
    ruled = {ruling.provider for ruling in load_byok_catalog_plan_rulings()}
    found: dict[str, ModelByokCatalogProvider] = {}
    for row in rows:
        provider = ModelByokCatalogProvider.model_validate(row)
        if provider.id in found:
            raise ByokCatalogListError(f"{provider.id!r} is listed more than once")
        if _is_plan(provider.id, provider.name) and provider.id not in ruled:
            raise ByokCatalogListError(
                f"{provider.id!r} is a plan with no row in {PLAN_RULINGS_PATH.name}"
            )
        found[provider.id] = provider
    return found


@lru_cache(maxsize=1)
def load_byok_catalog_withheld() -> tuple[ModelByokCatalogWithheld, ...]:
    """The listed providers withheld because their address does not work."""
    rows = _read_yaml(WITHHELD_PROVIDERS_PATH, WITHHELD_PROVIDERS_SCHEMA).get(
        "providers"
    )
    if not isinstance(rows, list):
        raise ByokCatalogListError(f"{WITHHELD_PROVIDERS_PATH} has no 'providers' list")
    held = tuple(ModelByokCatalogWithheld.model_validate(row) for row in rows)
    if len({w.provider for w in held}) != len(held):
        raise ByokCatalogListError(f"{WITHHELD_PROVIDERS_PATH} names one twice")
    return held


@lru_cache(maxsize=1)
def load_byok_catalog_added_providers() -> tuple[ModelByokCatalogAddedProvider, ...]:
    """The providers the operator named that models.dev does not list, each held to
    the list's rules: a fixed https URL off this machine, a plain id, and no plan."""
    rows = _read_yaml(ADDED_PROVIDERS_PATH, ADDED_PROVIDERS_SCHEMA).get("providers")
    if not isinstance(rows, list):
        raise ByokCatalogListError(f"{ADDED_PROVIDERS_PATH} has no 'providers' list")
    added: list[ModelByokCatalogAddedProvider] = []
    for row in rows:
        provider = ModelByokCatalogAddedProvider.model_validate(row)
        if _fixed_https_base(provider.api) != provider.api:
            raise ByokCatalogListError(f"{provider.id!r} has no fixed https base URL")
        if _is_plan(provider.id, provider.name):
            raise ByokCatalogListError(
                f"{provider.id!r} is a plan; plans need a ruling"
            )
        if any(a.id == provider.id for a in added):
            raise ByokCatalogListError(f"{provider.id!r} is added more than once")
        if provider_turned_off(provider.id) is None:  # OMN-26688
            added.append(provider)
    return tuple(added)


def main(argv: list[str] | None = None) -> int:
    """Regenerate the shipped list from a models.dev copy: ``<path to models.dev json>``."""
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        sys.stderr.write(
            "usage: python -m omnimarket.handlers.routing.byok_catalog_providers "
            "<models.dev json>\n"
        )
        return 2
    from omnimarket.handlers.routing.byok_provider_backends import (
        CATALOG_PATH,
        _read_plan_catalog,
        load_byok_not_offered_providers,
    )

    declared = _read_plan_catalog(CATALOG_PATH).values()
    hosts = frozenset(
        host
        for row in declared
        if not row.endpoint_from_registration
        for host in (urlsplit(row.endpoint_url).hostname,)
        if host
    )
    document = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    providers = select_catalog_providers(
        document,
        declared_ids=frozenset(row.provider for row in declared)
        | frozenset(load_byok_not_offered_providers()),
        declared_hosts=hosts,
        rulings=load_byok_catalog_plan_rulings(),
    )
    CATALOG_PROVIDERS_PATH.write_text(
        render_catalog_providers(providers), encoding="utf-8"
    )
    sys.stdout.write(f"wrote {len(providers)} providers to {CATALOG_PROVIDERS_PATH}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


