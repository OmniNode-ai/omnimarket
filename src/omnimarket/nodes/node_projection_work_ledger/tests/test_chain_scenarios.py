"""Golden and error chain tests of node_projection_work_ledger, generated from its chain_scenarios (OMN-19998).

Generated by node_event_chain_generator_compute 1.0.0; do not edit. Change the
scenarios in contract.yaml and regenerate. Each case publishes its input event on the
overlay's bus, runs the node's own handler through the runtime adapter and asserts the
events, ledger failure row and reading the case states. Each named break must turn
its case red, and the receipts of that proof are kept in chain_scenario_receipts.json.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from omnibase_core.enums.enum_chain_scenario_break import EnumChainScenarioBreak
from omnibase_core.models.contracts.subcontracts.model_chain_scenario_case import (
    ModelChainScenarioCase,
)

from omnimarket.handlers.chain_scenarios import support

pytestmark = pytest.mark.unit

NODE = support.load_node(Path(__file__).resolve().parents[1] / "contract.yaml")


@pytest.mark.parametrize("case", NODE.scenario.cases, ids=lambda c: c.case_name)
async def test_the_case_holds(case: ModelChainScenarioCase) -> None:
    await support.assert_case(NODE, case)


@pytest.mark.parametrize(
    ("case", "injected_break"),
    support.break_pairs(NODE),
    ids=lambda v: v.case_name if isinstance(v, ModelChainScenarioCase) else v.value,
)
async def test_the_named_break_turns_the_case_red(
    case: ModelChainScenarioCase, injected_break: EnumChainScenarioBreak
) -> None:
    receipt = await support.prove_break(NODE, case, injected_break)
    assert receipt.outcome == "red", (
        f"{case.case_name} stayed green under {injected_break.value}: the test cannot fail"
    )


async def test_the_kept_receipts_are_the_fresh_proof() -> None:
    support.keep_or_compare_receipts(NODE, await support.fresh_receipts(NODE))
