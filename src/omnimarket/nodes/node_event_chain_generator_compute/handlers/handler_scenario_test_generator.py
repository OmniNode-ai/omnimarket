"""Generate a node's golden and error chain test module from its typed scenarios.

The generator sits with the node scaffolder and the event-chain generator because the
module it writes is the one a scaffolded node gets beside its handler, and because it
needs the market's runner. The schema and the validator it consults are omnibase_core's:
it applies every rule of the core chain scenario validation contract except the receipts
rule, which can only be judged after the generated tests have run, and it refuses a
contract the validator would refuse. A scenario whose cases declare no break to survive
cannot yield a test that fails, so it yields no test.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import omnibase_core
import yaml
from omnibase_core.models.contracts.subcontracts.model_chain_scenario_receipt_set import (
    ModelChainScenarioReceiptSet,
)
from omnibase_core.models.contracts.subcontracts.model_chain_scenario_subcontract import (
    ModelChainScenarioSubcontract,
)
from omnibase_core.models.contracts.subcontracts.model_validator_subcontract import (
    ModelValidatorSubcontract,
)
from omnibase_core.validation.checker_chain_scenario import check_chain_scenarios

from omnimarket.nodes.node_event_chain_generator_compute.models.model_chain_scenario_declaration_error import (
    ChainScenarioDeclarationError,
)
from omnimarket.nodes.node_event_chain_generator_compute.models.model_generated_chain_case import (
    ModelGeneratedChainCase,
)
from omnimarket.nodes.node_event_chain_generator_compute.models.model_scenario_test_generation import (
    ModelScenarioTestGenerationRequest,
    ModelScenarioTestGenerationResult,
)

_VALIDATION_CONTRACT = (
    Path(omnibase_core.__file__).parent
    / "validation"
    / "contracts"
    / "chain_scenario.validation.yaml"
)
_RECEIPTS_RULE = "generated_test_cannot_fail"

_TEMPLATE = '''# SPDX-FileCopyrightText: 2026 OmniNode.ai Inc.
# SPDX-License-Identifier: MIT
"""Golden and error chain tests of @NODE@, generated from its chain_scenarios (OMN-19998).

Generated by node_event_chain_generator_compute @VERSION@; do not edit. Change the
scenarios in contract.yaml and regenerate. Each case publishes its input event on the
overlay's bus, runs the node's own handler through the runtime adapter and asserts the
events, ledger failure row and reading the case states. Each named break must turn
its case red, and the receipts of that proof are kept in @RECEIPTS@.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from omnibase_core.enums.enum_chain_scenario_break import EnumChainScenarioBreak
from omnibase_core.models.contracts.subcontracts.model_chain_scenario_case import (
    ModelChainScenarioCase,
)

from omnimarket.chain_scenarios import support

pytestmark = pytest.mark.unit

NODE = support.load_node(Path(__file__).resolve().parents[1] / "contract.yaml")


@pytest.mark.parametrize("case", NODE.scenario.cases, ids=lambda c: c.case_name)
async def test_the_case_holds(case: ModelChainScenarioCase) -> None:
    await support.assert_case(NODE, case)


@pytest.mark.parametrize(
    ("case", "injected_break"),
    support.break_pairs(NODE),
    ids=lambda v: v.case_name if isinstance(v, ModelChainScenarioCase) else v.value,
)
async def test_the_named_break_turns_the_case_red(
    case: ModelChainScenarioCase, injected_break: EnumChainScenarioBreak
) -> None:
    receipt = await support.prove_break(NODE, case, injected_break)
    assert receipt.outcome == "red", (
        f"{case.case_name} stayed green under {injected_break.value}: the test cannot fail"
    )


async def test_the_kept_receipts_are_the_fresh_proof() -> None:
    support.keep_or_compare_receipts(NODE, await support.fresh_receipts(NODE))
'''


def _validation_contract(*, judge_receipts: bool) -> ModelValidatorSubcontract:
    """The core validation contract; the receipts rule is judged only when receipts are given."""
    data = yaml.safe_load(_VALIDATION_CONTRACT.read_text(encoding="utf-8"))
    contract = ModelValidatorSubcontract.model_validate(data["validation"])
    if judge_receipts:
        return contract
    return contract.model_copy(
        update={
            "rules": [
                rule.model_copy(update={"enabled": False})
                if rule.rule_id == _RECEIPTS_RULE
                else rule
                for rule in contract.rules
            ]
        }
    )


class HandlerScenarioTestGenerator:
    """Pure: a contract document in, a test module out, or ChainScenarioDeclarationError."""

    def handle(
        self, request: ModelScenarioTestGenerationRequest
    ) -> ModelScenarioTestGenerationResult:
        document = dict(request.contract_document)
        receipt_set = (
            ModelChainScenarioReceiptSet.model_validate(request.kept_receipts)
            if request.kept_receipts is not None
            else None
        )
        rules = _validation_contract(judge_receipts=receipt_set is not None).rules
        issues = check_chain_scenarios(
            {request.node_name: document}, {request.node_name: receipt_set}, rules
        )
        errors = [issue for issue in issues if issue.severity == "error"]
        if errors:
            raise ChainScenarioDeclarationError(
                request.node_name,
                rule_ids=tuple(dict.fromkeys(str(issue.code) for issue in errors)),
                issues=tuple(f"{issue.code}: {issue.message}" for issue in errors),
            )
        scenario = ModelChainScenarioSubcontract.model_validate(
            document["chain_scenarios"]
        )
        source = (
            _TEMPLATE.replace("@NODE@", request.node_name)
            .replace("@VERSION@", request.generator_version)
            .replace("@RECEIPTS@", "chain_scenario_receipts.json")
        )
        return ModelScenarioTestGenerationResult(
            status="ok",
            generated_cases=tuple(
                ModelGeneratedChainCase(
                    case_name=case.case_name,
                    kind="GOLDEN" if case.kind.value == "GOLDEN" else "ERROR",
                    named_break=named_break.value,
                )
                for case in scenario.cases
                for named_break in case.breaks
            ),
            case_names=tuple(case.case_name for case in scenario.cases),
            break_pairs=sum(len(case.breaks) for case in scenario.cases),
            test_source=source,
            test_hash=hashlib.sha256(source.encode("utf-8")).hexdigest(),
        )


__all__ = ["HandlerScenarioTestGenerator"]
