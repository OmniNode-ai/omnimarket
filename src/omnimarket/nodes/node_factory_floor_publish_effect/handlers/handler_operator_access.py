"""Serve the operator-only reports to the operator's own devices and to nobody else.

The shared factory floor site is a public website of the tailnet. A report that is for the operator alone is
published beside it but is behind a gate in the web server: the server answers 403 to every source address that is
not one of the operator's own devices. This handler builds that gate on every publish, in this order:

1. read the tailnet status on the publishing host and take the addresses of the devices that the overlay's
   ``owner_login`` owns and whose platform is one of the operator's own device classes (no address is ever written
   down; the list is re-derived each run, so a new device or a retired one is followed);
2. write the allowed-address include to the access directory beside the serving directory, over ssh, atomically;
3. reload the web server container and read its configuration back: it must carry the gate marker and every
   allowed address;
4. only then write the operator-only report pages and data to the serving directory.

When step 1, 2 or 3 fails, the operator-only files are removed from the serving directory and the publish refuses
naming the cause: a server that does not carry the gate never serves the report to everyone. A missing or invalid
``owner_login`` key refuses before anything is read, and the refusal names the key.
"""

from __future__ import annotations

import hashlib
import ipaddress
import json
import os
import shlex
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path, PurePosixPath

from omnimarket.handlers.node_overlay_reader import load_structured_overlay
from omnimarket.nodes.node_factory_floor_publish_effect.handlers.handler_factory_floor_publish import (
    NODE_NAME,
    PublishRefusedError,
    Runner,
    copy_to_server,
    load_runtime,
    run_process,
    ssh_argv,
)
from omnimarket.nodes.node_factory_floor_publish_effect.handlers.handler_reports_publish import (
    MANIFEST_SCHEMA,
    HandlerReportsPublish,
)
from omnimarket.nodes.node_factory_floor_publish_effect.models.model_factory_floor_publish import (
    ModelFactoryFloorPublishOverlay,
    ModelFactoryFloorPublishRuntime,
    ModelOperatorAccessRequest,
    ModelOperatorAccessResult,
)

OWNER_KEY = "owner_login"


def resolve_operator_addresses(
    status: Mapping[str, object], owner_login: str, operator_os: Sequence[str]
) -> tuple[str, ...]:
    """The tailnet addresses of the devices ``owner_login`` owns whose platform is one of ``operator_os``.

    ``status`` is the document ``tailscale status --json`` prints: a ``User`` table of id to profile (with its
    ``LoginName``) and the ``Self`` and ``Peer`` devices, each with a ``UserID``, an ``OS`` and its ``TailscaleIPs``.
    The result is sorted and holds only valid IP addresses.
    """
    users = status.get("User")
    if not isinstance(users, Mapping):
        raise PublishRefusedError(
            "the tailnet status has no User table; cannot tell which devices the owner_login overlay key owns"
        )
    wanted = owner_login.strip().lower()
    owner_ids = {
        str(user_id)
        for user_id, profile in users.items()
        if isinstance(profile, Mapping)
        and str(profile.get("LoginName", "")).strip().lower() == wanted
    }
    peers = status.get("Peer")
    devices: list[object] = [status.get("Self")]
    if isinstance(peers, Mapping):
        devices.extend(peers.values())
    found: set[str] = set()
    for device in devices:
        if not isinstance(device, Mapping):
            continue
        if str(device.get("UserID")) not in owner_ids:
            continue
        if device.get("OS") not in operator_os:
            continue
        addresses = device.get("TailscaleIPs")
        if not isinstance(addresses, list):
            continue
        for raw in addresses:
            try:
                found.add(str(ipaddress.ip_address(str(raw))))
            except ValueError:
                continue
    return tuple(sorted(found, key=lambda a: (ipaddress.ip_address(a).version, a)))


def render_include(addresses: Sequence[str]) -> str:
    """The nginx include that admits ``addresses``; the server's own ``deny all`` follows it and refuses the rest."""
    lines = [
        "# Generated by the factory floor publish on every run. Do not edit.",
        "# The operator's own devices; everything else is refused by the deny rule that follows this include.",
    ]
    lines.extend(f"allow {ipaddress.ip_address(a)};" for a in addresses)
    return "\n".join(lines) + "\n"


class HandlerOperatorAccess:
    """Boundary of the operator-only publish: the tailnet read, the include, the reload and the copies happen here."""

    def __init__(self, runner: Runner = run_process) -> None:
        self._run = runner

    def handle(
        self,
        request: ModelOperatorAccessRequest,
        environ: Mapping[str, str] | None = None,
    ) -> ModelOperatorAccessResult:
        """Raises ``PublishRefusedError`` or ``NodeOverlayError`` naming what is missing; the private files are withdrawn first."""
        env = os.environ if environ is None else environ
        rt = load_runtime()
        overlay = load_structured_overlay(
            NODE_NAME,
            ModelFactoryFloorPublishOverlay,
            env,
            explicit=request.overlay,
            file_env=rt.overlay_file_env,
        )
        home_value = (request.home or env.get(rt.home_env, "")).strip()
        if not home_value:
            raise PublishRefusedError(
                f"{rt.home_env} is not set (fail fast, no default): export it or pass --omni-home"
            )
        try:
            include, changed, count = self._build_gate(rt, overlay)
        except PublishRefusedError as exc:
            self._withdraw(rt, overlay)
            raise PublishRefusedError(
                f"the operator-only reports are withdrawn from the serving directory: {exc}"
            ) from exc
        published, unread = (
            ((), ())
            if request.skip_reports
            else self._publish(
                rt, overlay, home_value, request.now or datetime.now(UTC)
            )
        )
        return ModelOperatorAccessResult(
            admitted_devices=count,
            include_sha256=hashlib.sha256(include).hexdigest(),
            include_changed=changed,
            published=published,
            unread=unread,
        )

    def _remote(
        self,
        rt: ModelFactoryFloorPublishRuntime,
        overlay: ModelFactoryFloorPublishOverlay,
        command: str,
    ) -> tuple[int, bytes, bytes]:
        done = self._run(
            ssh_argv(rt, overlay, command),
            None,
            rt.transport.transfer_timeout_seconds,
        )
        return done.returncode, done.stdout, done.stderr

    def _build_gate(
        self,
        rt: ModelFactoryFloorPublishRuntime,
        overlay: ModelFactoryFloorPublishOverlay,
    ) -> tuple[bytes, bool, int]:
        """Write the include, reload the server and read its configuration back; the include, whether it changed, the count."""
        access = rt.operator_reports.access
        done = self._run(
            list(access.tailscale_argv), None, rt.transport.connect_timeout_seconds
        )
        if done.returncode != 0:
            raise PublishRefusedError(
                f"the tailnet status could not be read (exit {done.returncode}); "
                "the allowed devices cannot be derived"
            )
        try:
            status = json.loads(done.stdout)
        except ValueError:
            raise PublishRefusedError("the tailnet status is not JSON") from None
        if not isinstance(status, dict):
            raise PublishRefusedError("the tailnet status is not a JSON object")
        addresses = resolve_operator_addresses(
            status, overlay.owner_login, access.operator_os
        )
        if not addresses:
            raise PublishRefusedError(
                f"no tailnet device of the platforms {list(access.operator_os)} is owned by the login in the "
                f"{OWNER_KEY} overlay key; check that the key matches a login in the tailnet status"
            )
        include = render_include(addresses).encode("utf-8")
        access_dir = str(
            PurePosixPath(overlay.remote_dir).parent / access.access_dirname
        )
        include_path = str(PurePosixPath(access_dir) / access.include_name)
        code, current, _ = self._remote(
            rt, overlay, f"cat -- {shlex.quote(include_path)}"
        )
        changed = code != 0 or current != include
        if changed:
            copy_to_server(
                self._run,
                rt,
                overlay,
                access.include_name,
                include,
                root=access_dir,
            )
        container = shlex.quote(access.container_name)
        code, _, _ = self._remote(
            rt, overlay, f"docker exec {container} nginx -s reload"
        )
        if code != 0:
            raise PublishRefusedError(
                f"the web server container {access.container_name} could not be reloaded (exit {code})"
            )
        code, dump, _ = self._remote(rt, overlay, f"docker exec {container} nginx -T")
        text = dump.decode("utf-8", "replace")
        if code != 0 or access.gate_marker not in text:
            raise PublishRefusedError(
                f"the web server's configuration does not carry the gate ({access.gate_marker!r}); "
                "redeploy docker/docker-compose.factory-floor-web.yml from the current infrastructure checkout"
            )
        missing = [a for a in addresses if f"allow {a};" not in text]
        if missing:
            raise PublishRefusedError(
                f"the web server does not read the allowed-address include ({len(missing)} of "
                f"{len(addresses)} addresses absent); mount the access directory at /etc/nginx/access"
            )
        return include, changed, len(addresses)

    def _private_names(self, rt: ModelFactoryFloorPublishRuntime) -> list[str]:
        names: list[str] = []
        for entry in rt.operator_reports.entries:
            names.extend(page.remote for page in entry.pages)
            names.extend(item.remote for item in entry.data)
        names.append(rt.operator_reports.manifest)
        return names

    def _withdraw(
        self,
        rt: ModelFactoryFloorPublishRuntime,
        overlay: ModelFactoryFloorPublishOverlay,
    ) -> None:
        """Remove the operator-only files from the serving directory; a failed removal is as loud as a failed gate."""
        base = PurePosixPath(overlay.remote_dir)
        paths = " ".join(shlex.quote(str(base / n)) for n in self._private_names(rt))
        code, _, _ = self._remote(rt, overlay, f"rm -f -- {paths}")
        if code != 0:
            raise PublishRefusedError(
                f"the operator-only reports could not be withdrawn from the serving directory (exit {code}) "
                "and the web server does not carry the gate"
            )

    def _publish(
        self,
        rt: ModelFactoryFloorPublishRuntime,
        overlay: ModelFactoryFloorPublishOverlay,
        home_value: str,
        now: datetime,
    ) -> tuple[tuple[str, ...], tuple[str, ...]]:
        home = Path(home_value)
        published: list[str] = []
        unread: list[str] = []
        manifest_entries: list[dict[str, object]] = []
        for entry in rt.operator_reports.entries:
            data_rows: list[dict[str, object]] = []
            for item in entry.data:
                row, payload = HandlerReportsPublish.read_data(home, item)
                data_rows.append(row)
                if payload is None:
                    unread.append(f"{entry.id}:{item.remote}")
                    continue
                copy_to_server(self._run, rt, overlay, item.remote, payload)
                published.append(item.remote)
            for page in entry.pages:
                copy_to_server(
                    self._run,
                    rt,
                    overlay,
                    page.remote,
                    HandlerReportsPublish.read_page(page.page_relpath),
                )
                published.append(page.remote)
            manifest_entries.append(
                HandlerReportsPublish.manifest_entry(entry, data_rows)
            )
        manifest = json.dumps(
            {
                "schema": MANIFEST_SCHEMA,
                "published_at": now.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "reports": manifest_entries,
            },
            sort_keys=True,
            indent=1,
        ).encode("utf-8")
        copy_to_server(self._run, rt, overlay, rt.operator_reports.manifest, manifest)
        published.append(rt.operator_reports.manifest)
        return tuple(published), tuple(unread)


