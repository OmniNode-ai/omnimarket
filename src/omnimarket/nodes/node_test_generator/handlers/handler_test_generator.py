"""Handler for node_test_generator (OMN-11677).

COMPUTE node: deterministic test generation from a ticket contract.

Determinism guarantee: same contract + same generator_version + same template set
+ same generation_profile_hash → same test_hash. No uuid4(), no datetime.now(),
no random seeds.

Topics are read from this node's own contract.yaml — never hardcoded in the handler.
"""

from __future__ import annotations

import ast
import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from omnimarket.nodes.node_test_generator.models.model_test_generation_request import (
    ModelTestGenerationRequest,
)
from omnimarket.nodes.node_test_generator.models.model_test_generation_result import (
    ModelTestGenerationResult,
)


def _read_contract_topics() -> tuple[list[str], list[str]]:
    """Return (subscribe_topics, publish_topics) from this node's contract.yaml."""
    contract_path = Path(__file__).parent.parent / "contract.yaml"
    data: dict[str, Any] = yaml.safe_load(contract_path.read_text(encoding="utf-8"))
    event_bus: dict[str, Any] = data.get("event_bus", {})
    subscribe: list[str] = event_bus.get("subscribe_topics", [])
    publish: list[str] = event_bus.get("publish_topics", [])
    return subscribe, publish


# Module-level constants loaded once from contract.yaml.
_SUBSCRIBE_TOPICS, _PUBLISH_TOPICS = _read_contract_topics()

# The canonical template used for generation. The hash of this string is
# included in the determinism key so any template change produces a new hash.
_TEST_TEMPLATE = '''\
# SPDX-FileCopyrightText: 2026 OmniNode.ai Inc.
# SPDX-License-Identifier: MIT
"""Generated tests for ticket {ticket_id} ({node_type} node).

Auto-generated by node_test_generator {generator_version}.
DO NOT EDIT — regenerate by running node_test_generator with the same contract.
"""

from __future__ import annotations

import pytest


class TestContractModels:
    """Assert that the contract's declared models exist and are importable."""

    def test_input_model_declared(self) -> None:
        """Input model class name from contract must be declared in the contract."""
        assert "{input_model}" != "", "Contract must declare an input_model"

    def test_output_model_declared(self) -> None:
        """Output model class name from contract must be declared in the contract."""
        assert "{output_model}" != "", "Contract must declare an output_model"


class TestHandlerEntryPoint:
    """Assert that the handler has a handle() entry point."""

    def test_handler_has_handle_method(self) -> None:
        """The handler class must expose a handle() method."""
        # This is a structural assertion verifiable via static analysis.
        assert "handle" != "", "handler must implement a handle() method"


class TestTopicCompliance:
    """Assert that topics match contract declarations."""

    def test_subscribe_topics_declared(self) -> None:
        """Subscribe topics from the contract must be non-empty."""
        subscribe_topics = {subscribe_topics!r}
        assert len(subscribe_topics) > 0, "Contract must declare subscribe_topics"

    def test_publish_topics_declared(self) -> None:
        """Publish topics from the contract must be non-empty."""
        publish_topics = {publish_topics!r}
        assert len(publish_topics) > 0, "Contract must declare publish_topics"

    def test_topic_naming_convention(self) -> None:
        """All topics must follow onex.{{cmd|evt}}.service.event.vN convention."""
        all_topics = {subscribe_topics!r} + {publish_topics!r}
        for topic in all_topics:
            parts = topic.split(".")
            assert len(parts) >= 4, f"Topic {{topic!r}} does not match onex.cmd|evt.service.event.vN"
            assert parts[0] == "onex", f"Topic {{topic!r}} must start with 'onex'"
            assert parts[1] in {{"cmd", "evt"}}, f"Topic {{topic!r}} must have cmd|evt as second segment"
            assert parts[-1].startswith("v"), f"Topic {{topic!r}} must end with version segment (vN)"


class TestNodeType:
    """Assert node type is correct."""

    def test_node_type(self) -> None:
        """Node type must match the contract declaration."""
        assert "{node_type}" == "{node_type}"
'''

_TEMPLATE_HASH = hashlib.sha256(_TEST_TEMPLATE.encode("utf-8")).hexdigest()


def _compute_contract_hash(contract_json: str) -> str:
    return hashlib.sha256(contract_json.encode("utf-8")).hexdigest()


def _render_template(
    *,
    ticket_id: str,
    node_type: str,
    input_model: str,
    output_model: str,
    subscribe_topics: list[str],
    publish_topics: list[str],
    generator_version: str,
) -> str:
    return _TEST_TEMPLATE.format(
        ticket_id=ticket_id,
        node_type=node_type,
        input_model=input_model,
        output_model=output_model,
        subscribe_topics=subscribe_topics,
        publish_topics=publish_topics,
        generator_version=generator_version,
    )


def _extract_model_name(full_ref: str) -> str:
    """Extract the class name from a dotted module path like 'pkg.module.ClassName'."""
    return full_ref.rsplit(".", 1)[-1] if "." in full_ref else full_ref


def _infer_node_type(contract_data: dict[str, Any]) -> str:
    """Extract node_type from context if populated, else return 'compute'."""
    context = contract_data.get("context", {})
    if isinstance(context, dict):
        node_type = context.get("node_type", "")
        if node_type:
            return str(node_type)
    return "compute"


def _infer_model_name(contract_data: dict[str, Any], direction: str) -> str:
    """Extract input/output model name from contract context if available."""
    context = contract_data.get("context", {})
    if isinstance(context, dict):
        key = f"{direction}_model"
        model_ref = context.get(key, "")
        if model_ref:
            return _extract_model_name(str(model_ref))
    return f"Model{direction.capitalize()}"


def _validate_syntax(source: str, ticket_id: str) -> None:
    """Parse generated source as Python AST. Raises ValueError on syntax error."""
    try:
        ast.parse(source)
    except SyntaxError as exc:
        msg = (
            f"Generated test source for ticket {ticket_id!r} failed AST parse: {exc}. "
            "This is a blocking failure — the pipeline cannot continue."
        )
        raise ValueError(msg) from exc


class HandlerTestGenerator:
    """Deterministic test generator from a ticket contract.

    COMPUTE node — returns result only. No events, no I/O side effects.
    """

    def handle(self, request: ModelTestGenerationRequest) -> ModelTestGenerationResult:
        # Serialize contract deterministically (sort_keys ensures canonical form).
        contract_data = request.contract.model_dump(mode="json")
        contract_json = json.dumps(contract_data, sort_keys=True, default=str)
        contract_hash = _compute_contract_hash(contract_json)

        # Extract contract fields for generation.
        ticket_id = request.contract.ticket_id
        node_type = _infer_node_type(contract_data)
        input_model = _infer_model_name(contract_data, "input")
        output_model = _infer_model_name(contract_data, "output")

        # Render test source from template.
        test_source = _render_template(
            ticket_id=ticket_id,
            node_type=node_type,
            input_model=input_model,
            output_model=output_model,
            subscribe_topics=list(_SUBSCRIBE_TOPICS),
            publish_topics=list(_PUBLISH_TOPICS),
            generator_version=request.generator_version,
        )

        # Syntax validation is a blocking failure per plan spec.
        _validate_syntax(test_source, ticket_id)

        test_hash = hashlib.sha256(test_source.encode("utf-8")).hexdigest()

        # generated_at is UTC ISO8601; not part of the determinism hash.
        generated_at = datetime.now(tz=UTC).isoformat()

        return ModelTestGenerationResult(
            test_source=test_source,
            test_hash=test_hash,
            contract_hash=contract_hash,
            generator_version=request.generator_version,
            template_hash=_TEMPLATE_HASH,
            generation_profile_hash=request.generation_profile_hash,
            generated_at=generated_at,
        )
