def _state(
    handler: HandlerLaneWorkReducer,
    name: str,
    fields: dict[str, Any],
    config: ModelLaneWorkReducerConfig,
):
    state = handler.initial_state(name, config=config)
    update = dict(fields)
    if update.pop("tiers", 0):
        update["help_tiers"] = TIERS
        update["help_tier_index"] = 0
    if "handoff_answered_at" in update:
        update["handoff_answered_at"] = datetime.fromisoformat(
            update["handoff_answered_at"]
        )
    return state.model_copy(update=update)


@pytest.mark.parametrize(
    ("name", "origin", "kind", "event", "fields", "target", "action", "action_type"),
    EDGE_TABLE,
    ids=[row[0] for row in EDGE_TABLE],
)
def test_every_edge(
    name, origin, kind, event, fields, target, action, action_type
) -> None:
    config = ModelLaneWorkReducerConfig(help_tiers=())
    handler = HandlerLaneWorkReducer()
    state = _state(handler, origin, fields, config)
    event = dict(event)
    if kind == "deadline_passed":
        event["deadline_attempt"] = state.armed_deadlines[event["deadline"]]
    result = handler.reduce(
        state,
        ModelLaneWorkFoldInput(kind=kind, **event),
        "2026-11-26T09:30:00Z",
        config,
    )
    assert result.outcome == "transition", result.refusal
    assert result.transition_name == name
    assert result.state.name == target
    assert result.from_state == origin
    assert len(result.intents) == 1
    intent = result.intents[0]
    assert intent.name == action
    assert intent.kind == (
        "agent"
        if action_type == "agent"
        else "terminal"
        if action_type == "terminal"
        else action
    )
    assert intent.action_id.startswith(state.workflow_id)


