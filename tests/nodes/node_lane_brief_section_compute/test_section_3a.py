def test_the_section_renders_the_ten_parts_in_the_standard_order() -> None:
    result = HandlerLaneBriefSection().handle(request())
    assert result.status is EnumLaneBriefSectionStatus.RENDERED
    assert result.section_3a == GOLDEN
    assert result.failure_class is None


def test_the_same_request_renders_the_same_bytes_and_hash() -> None:
    first = HandlerLaneBriefSection().handle(request())
    second = HandlerLaneBriefSection().handle(request())
    assert first == second
    assert first.section_3a is not None
    assert (
        first.section_sha256
        == hashlib.sha256(first.section_3a.encode("utf-8")).hexdigest()
    )


def test_an_empty_reader_output_renders_an_empty_fence() -> None:
    holds_only = tuple((s, "" if s == SLOT_HOLDS else t) for s, t in OPEN_WORK_ENTRIES)
    result = HandlerLaneBriefSection().handle(
        request(open_work=resolved(F.OPEN_WORK, holds_only))
    )
    assert result.section_3a is not None
    assert "rc=0)\n\n```text\n```\n\n### 3a.3" in result.section_3a


def test_no_route_line_leaves_the_model_line_alone() -> None:
    result = HandlerLaneBriefSection().handle(request(route_line=None))
    assert result.section_3a is not None
    assert "model=sonnet effort=high\n\n### 3a.6 Consent" in result.section_3a


# AC2: the refuse-on-missing rule survives as REQUIRED_FACTOR_MISSING.


@pytest.mark.parametrize(
    "factor_field",
    ["lane_rules", "operator_rulings", "open_work"],
)
def test_a_factor_the_caller_did_not_supply_refuses(factor_field: str) -> None:
    result = HandlerLaneBriefSection().handle(request(**{factor_field: None}))
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.failure_class is EnumContextPackFailure.REQUIRED_FACTOR_MISSING
    assert result.section_3a is None
    assert len(result.missing_factors) == 1


@pytest.mark.parametrize(
    "status",
    [
        EnumContextSourceStatus.UNRESOLVED,
        EnumContextSourceStatus.DENIED,
        EnumContextSourceStatus.UNAVAILABLE,
    ],
)
def test_a_brief_whose_cited_ruling_source_did_not_resolve_does_not_render(
    status: EnumContextSourceStatus,
) -> None:
    result = HandlerLaneBriefSection().handle(
        request(operator_rulings=ModelContextSourceResult(status=status))
    )
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.failure_class is EnumContextPackFailure.REQUIRED_FACTOR_MISSING
    assert result.missing_factors == (F.OPERATOR_RULINGS,)
    assert result.section_3a is None


def test_a_cited_landing_ruling_no_entry_backs_does_not_render() -> None:
    rulings = tuple(
        (slot, text) for slot, text in RULING_ENTRIES if slot != SLOT_LANDING_RULING
    )
    result = HandlerLaneBriefSection().handle(
        request(operator_rulings=resolved(F.OPERATOR_RULINGS, rulings))
    )
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.failure_class is EnumContextPackFailure.REQUIRED_FACTOR_MISSING
    assert f"{F.OPERATOR_RULINGS.value}:{SLOT_LANDING_RULING}" in result.missing_slots


def test_a_landing_ruling_stamp_the_rows_do_not_carry_does_not_render() -> None:
    result = HandlerLaneBriefSection().handle(
        request(landing_ruling="2026-01-01T00:00:00Z")
    )
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.unbacked_ruling_stamps == ("2026-01-01T00:00:00Z",)


def test_a_landing_ruling_row_of_another_lane_does_not_back_the_citation() -> None:
    result = HandlerLaneBriefSection().handle(request(landing_ruling_lane="other-lane"))
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.unbacked_ruling_stamps == (LANDING_STAMP,)


def test_every_cited_ruling_stamp_must_be_backed() -> None:
    backed = HandlerLaneBriefSection().handle(
        request(cited_ruling_stamps=(OTHER_STAMP,))
    )
    assert backed.status is EnumLaneBriefSectionStatus.RENDERED
    missing = HandlerLaneBriefSection().handle(
        request(cited_ruling_stamps=(OTHER_STAMP, "2026-02-02T02:02:02Z"))
    )
    assert missing.status is EnumLaneBriefSectionStatus.REFUSED
    assert missing.unbacked_ruling_stamps == ("2026-02-02T02:02:02Z",)
    assert missing.failure_class is EnumContextPackFailure.REQUIRED_FACTOR_MISSING


def test_a_missing_slot_in_a_resolved_factor_refuses_and_names_it() -> None:
    work = tuple((s, t) for s, t in OPEN_WORK_ENTRIES if s != SLOT_HOLDS)
    result = HandlerLaneBriefSection().handle(
        request(open_work=resolved(F.OPEN_WORK, work))
    )
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.missing_slots == (f"{F.OPEN_WORK.value}:{SLOT_HOLDS}",)


def test_a_slot_given_twice_is_ambiguous_and_refuses() -> None:
    work = (*OPEN_WORK_ENTRIES, OPEN_WORK_ENTRIES[0])
    result = HandlerLaneBriefSection().handle(
        request(open_work=resolved(F.OPEN_WORK, work))
    )
    assert result.status is EnumLaneBriefSectionStatus.REFUSED
    assert result.missing_slots == (f"{F.OPEN_WORK.value}:inbox:ambiguous",)
