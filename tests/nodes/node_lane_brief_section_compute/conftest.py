def entry(factor: EnumContextFactor, slot: str, text: str) -> ModelContextSourceEntry:
    return ModelContextSourceEntry(
        factor=factor,
        text=text,
        source_ref=slot,
        text_sha256=hashlib.sha256(text.encode("utf-8")).hexdigest(),
        status=EnumContextSourceStatus.RESOLVED,
        as_of=AS_OF,
    )


def resolved(
    factor: EnumContextFactor, entries: tuple[tuple[str, str], ...]
) -> ModelContextSourceResult:
    return ModelContextSourceResult(
        status=EnumContextSourceStatus.RESOLVED,
        entries=tuple(entry(factor, slot, text) for slot, text in entries),
    )


